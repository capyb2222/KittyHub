        for i = 1, #text do
            local value = VALUE[text:byte(i)]
            if value then
                bits = bits * 64 + value
                held = held + 6
                if held >= 8 then
                    held = held - 8
                    local scale = 2 ^ held
                    out[#out + 1] = string.char(math.floor(bits / scale) % 256)
                    bits = bits % scale
                end
            end
        end
        return table.concat(out)
